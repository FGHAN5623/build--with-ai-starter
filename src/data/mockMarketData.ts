// Helper to generate realistic candles for charts
export function generateCandles(basePrice: number, points: number = 60, volatility: number = 0.015, trend: number = 0.0005): CandleData[] {
  const candles: CandleData[] = [];
  let currentPrice = basePrice * (1 - points * trend * 0.4);
  const now = Date.now();
  const step = 3600 * 1000; // 1 hour step

  for (let i = 0; i < points; i++) {
    const timestamp = now - (points - i) * step;
    const date = new Date(timestamp);
    const time = `${date.getHours().toString().padStart(2, '0')}:${date.getMinutes().toString().padStart(2, '0')}`;
    
    // Random walk with trend
    const change = currentPrice * (Math.random() - 0.49 + trend) * volatility;
    const open = currentPrice;
    const close = Math.max(1, open + change);
    const high = Math.max(open, close) + Math.random() * currentPrice * volatility * 0.5;
    const low = Math.min(open, close) - Math.random() * currentPrice * volatility * 0.5;
    const volume = Math.floor((Math.random() * 500000 + 100000) * (1 + Math.abs(change / open) * 5));

    candles.push({
      time,
      timestamp,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });

    currentPrice = close;
  }

  return candles;
}

// Generate sparkline values
function generateSparkline(basePrice: number, points: number = 24, changePct: number = 1.5): number[] {
  const values: number[] = [basePrice * (1 - changePct / 100)];
  for (let i = 1; i < points - 1; i++) {
    const prev = values[i - 1];
    values.push(prev * (1 + (Math.random() - 0.48) * 0.008));
  }
  values.push(basePrice);
  return values.map(v => Number(v.toFixed(2)));
}

